const fixtures = currentSourcePath().parentDir / "fixtures"

proc u32(v: uint32): string =
  for i in 0 ..< 4:
    result.add(char((v shr (i * 8)) and 0xff))

proc record(cellType: int, flags: uint32, payload: string): string =
  # hand-built v5 record: version, type, reserved, extras, flags, fields
  "\x05" & char(cellType) & "\x00\x00" & u32(0) & u32(flags) & payload

proc oneRowTable(id: uint64, name: string, cells: seq[string],
    extraStore = ""): string =
  # info `id` -> model id+1 -> tile id+2, with cell records in one row;
  # text cells key into the string list at id+3
  var buf, offsets: string
  for c in cells:
    offsets.add(char(buf.len and 0xff) & char(buf.len shr 8))
    buf.add(c)
  let tile = pbBytes(5, pbUint(1, 0) & pbBytes(6, buf) & pbBytes(7, offsets))
  let store = pbBytes(3, pbBytes(1, pbUint(1, 0) & pbRef(2, id + 2))) &
    pbRef(4, id + 3) & extraStore
  iwaObject(id, tstTableInfoArchive, pbRef(2, id + 1)) &
    iwaObject(id + 1, tstTableModelArchive, pbBytes(4, store) &
      pbUint(6, 1) & pbUint(7, uint64(cells.len)) & pbBytes(8, name)) &
    iwaObject(id + 2, tstTileArchive, tile)

proc strings(id: uint64, texts: seq[string]): string =
  # a string list whose keys are 1, 2, ...
  var entries: string
  for i, s in texts:
    entries.add(pbBytes(3, pbUint(1, uint64(i + 1)) & pbBytes(3, s)))
  iwaObject(id, tstTableDataList, entries)

proc textTable(id: uint64, name, text: string): string =
  oneRowTable(id, name, @[record(3, 0x8, u32(1))]) & strings(id + 3, @[text])

proc storage(id: uint64, text: string): string =
  iwaObject(id, tswpStorageArchive, pbBytes(3, text))

proc shape(id, storageId: uint64): string =
  iwaObject(id, tswpShapeInfoArchive, pbRef(2, storageId))

proc synthetic(name, stream: string): IworkDocument =
  let dir = getTempDir() / "iwork_content_" & name
  removeDir(dir)
  writeBundle(dir, stream)
  # entries load eagerly, so the bundle can go right away
  result = openDocument(dir)
  removeDir(dir)

suite "content: rich text cells":
  # expected values come from numbers-parser's own tests/test_bullets.py
  test "bullets fixture mixes plain and rich text cells":
    let t = openDocument(fixtures / "numbers-parser-test-bullets.numbers").tables[0]
    check t.cell(0, 0).text == "some\nnewline\ntext" # plain text cell
    check t.cell(0, 1).text == "this\nis some\nbulleted\ntext"
    check t.cell(1, 1).text == "this\nis some\nnumbered\ntext"
    check t.cell(2, 1).text == "this\nis some\nlettered\ntext"
    check t.cell(2, 0).text == "t"

  test "hyperlink cells keep their full text":
    let t = openDocument(fixtures / "numbers-parser-test-hlinks.numbers").tables[0]
    check t.cell(0, 0).text ==
      "visit BBC News for the news and Google to find stuff"
    check "Google" in t.cell(1, 0).text
    check t.cell(2, 0).text.splitLines.len == 4 # four bullets
    check t.cell(3, 0).text.splitLines.len == 4

  test "real rich text fixtures report clean":
    for (name, known) in [("numbers-parser-test-bullets.numbers", "lettered"),
        ("numbers-parser-test-hlinks.numbers", "BBC News")]:
      let report = openDocument(fixtures / name).getTextReport(strict = true)
      check report.warnings.len == 0
      check known in report.text

  test "an unresolved payload stays empty text and gets flagged":
    # key 1 resolves through the rich list at 20, key 2 has no entry
    let rich = pbRef(17, 20)
    let doc = synthetic("rich.numbers",
      iwaObject(1, tnDocumentArchive, pbRef(1, 2)) &
      iwaObject(2, tnSheetArchive, pbBytes(1, "S") & pbRef(2, 10)) &
      oneRowTable(10, "T", @[record(9, 0x10, u32(1)), record(9, 0x10, u32(2)),
        record(0, 0, "")], rich) &
      strings(13, @[]) &
      iwaObject(20, tstTableDataList,
        pbBytes(3, pbUint(1, 1) & pbRef(9, 21))) &
      iwaObject(21, tstRichTextPayloadArchive, pbRef(1, 22)) &
      storage(22, "styled words"))
    let t = doc.tables[0]
    check t.cell(0, 0).text == "styled words"
    check t.cell(0, 1).kind == ckText
    check t.cell(0, 1).text == ""
    check t.cell(0, 2).kind == ckEmpty # a genuinely empty cell isn't flagged
    let report = doc.getTextReport()
    check report.warnings.len == 1
    check report.warnings[0].kind == ewMissingReference
    check "1 rich text cells don't resolve" in report.warnings[0].message
    check "styled words" in report.text
    expect IworkFormatError:
      discard doc.getTextReport(strict = true)

suite "content: keynote tables and groups":
  # grouped-tables.key was generated by make-grouped-tables-key.applescript,
  # so its contents are known up front
  let doc = openDocument(fixtures / "grouped-tables.key")
  let slides = doc.slides

  test "slide tables decode through the slide's drawables":
    check slides.len == 4
    check slides[0].tables.len == 1
    let t = slides[0].tables[0]
    check t.name == "Sales"
    check t.numRows == 3
    check t.numCols == 3
    check toCsv(t) == "Region,Q1,Q2\nNorth,10,12\nSouth,7,9"
    for i in 1 .. 3:
      check slides[i].tables.len == 0

  test "text inside nested groups is found, in group order":
    check slides[2].body == @["Group alpha", "Group beta", "Outer gamma"]
    check slides[2].presenterNotes == "Grouped slide note"

  test "getText reads tables after the slide text, before notes":
    check doc.getText() == [
      "Quarterly numbers", "Sales by region", "Region\tQ1\tQ2",
      "North\t10\t12", "South\t7\t9", "Mention the north",
      "Hidden slide", "Only in the skipped slide", "Skipped slide note",
      "Group alpha", "Group beta", "Outer gamma", "Grouped slide note",
      "Closing", "Thanks"].join("\n")
    check doc.getTextReport(strict = true).warnings.len == 0

  test "group cycles, duplicates, orphans, and master tables":
    # slide 4 lists shape 11 under body and drawables, group 10 holds
    # group 12 which points back at 10; table 50 sits in the inner group.
    # table 30 is referenced by nothing and table 40 only by the master
    let doc = synthetic("groups.key",
      iwaObject(1, knDocumentArchive, pbRef(2, 2)) &
      iwaObject(2, knShowArchive, pbBytes(3, pbRef(2, 3))) &
      iwaObject(3, knSlideNodeArchive, pbRef(2, 4)) &
      iwaObject(4, knSlideArchive, pbRef(1, 5) & pbRef(6, 11) &
        pbRef(7, 10) & pbRef(7, 11)) &
      iwaObject(5, knSlideArchive, pbRef(7, 40)) &
      iwaObject(10, tsdGroupArchive, pbRef(2, 12) & pbRef(2, 11)) &
      iwaObject(12, tsdGroupArchive, pbRef(2, 10) & pbRef(2, 13) &
        pbRef(2, 50)) &
      shape(11, 20) & shape(13, 21) &
      storage(20, "shared box") & storage(21, "deep box") &
      textTable(30, "Orphan", "orphan cell") &
      textTable(40, "Master", "master cell") &
      textTable(50, "Grouped", "slide cell"))
    check doc.getText() == "shared box\ndeep box\nslide cell"
    check doc.slides[0].tables.len == 1
    check doc.slides[0].tables[0].name == "Grouped"

suite "content: pages tables":
  # inline-tables.pages was generated by make-inline-tables-pages.applescript
  let doc = openDocument(fixtures / "inline-tables.pages")
  let first = "Ünïcödé façade naïve café " & "🙂".repeat(12)
  let second = "Second paragraph " & "🙂".repeat(8)

  test "an inline table lands after its paragraph, a floating one last":
    # the multibyte text before the anchor checks the utf-16 index
    # mapping: counting bytes instead would place the table too early
    check doc.getText() == [first, second, "Part\tCount", "Bolt\t40",
      "Nut\t55", "Closing paragraph after the table.", "Item\tPrice",
      "Widget\t5"].join("\n")
    check doc.getTextReport(strict = true).warnings.len == 0

  test "bodyText stays paragraphs only":
    check doc.bodyText == @[first, second,
      "Closing paragraph after the table."]

  test "table rows carry their table names":
    var names: seq[string]
    for blk in doc.textBlocks:
      if blk.kind == tbTableRow and blk.table notin names:
        names.add(blk.table)
    check names == @["Inventory", "Prices"]

proc pagesStream(): string =
  # header, body (with a paragraph that repeats the footer wording and an
  # inline table), footer, a text box, a floating table, and an orphan
  let body = "Body one 🙂\nFooter text\n\xef\xbf\xbc\nBody two"
  let anchor = toRunes("Body one 🙂\nFooter text\n").len + 1 # 🙂 is 2 units
  iwaObject(1, tpDocumentArchive, pbRef(3, 60) & pbRef(4, 2)) &
    iwaObject(2, tswpStorageArchive, pbBytes(3, body) &
      pbBytes(9, pbBytes(1, pbUint(1, uint64(anchor)) & pbRef(2, 5))) &
      pbBytes(17, pbBytes(1, pbUint(1, 0) & pbRef(2, 3)))) &
    iwaObject(3, tpSectionArchive, pbRef(23, 4)) &
    iwaObject(4, tpHeadersFootersArchive, pbRef(1, 6) & pbRef(2, 7)) &
    iwaObject(5, 2003, pbRef(1, 80)) &
    storage(6, "Header text") & storage(7, "Footer text") &
    shape(8, 9) & storage(9, "Box text") &
    iwaObject(60, tpFloatingDrawablesArchive,
      pbBytes(1, pbUint(1, 0) & pbBytes(4, pbRef(1, 70)))) &
    textTable(70, "Floating", "floating cell") &
    textTable(80, "Inline", "inline cell") &
    textTable(90, "Orphan", "orphan cell")

suite "content: extraction options":
  let key = openDocument(fixtures / "grouped-tables.key")
  let pages = synthetic("options.pages", pagesStream())

  test "defaults change nothing":
    for doc in [key, pages, openDocument(fixtures / "rich.numbers")]:
      check doc.getText(ExtractOptions()) == doc.getText()
      check doc.textBlocks(ExtractOptions()) == doc.textBlocks

  test "synthetic pages reads in the documented order":
    check pages.getText() == ["Header text", "Body one 🙂", "Footer text",
      "inline cell", "Body two", "Footer text", "Box text",
      "floating cell"].join("\n")

  test "excludeNotes drops only notes":
    let text = key.getText(ExtractOptions(excludeNotes: true))
    var want: seq[string]
    for line in key.getText().splitLines:
      if line notin ["Mention the north", "Skipped slide note",
          "Grouped slide note"]:
        want.add(line)
    check text == want.join("\n")

  test "excludeSkippedSlides drops the whole skipped slide only":
    check key.slides[1].isSkipped
    let blocks = key.textBlocks(ExtractOptions(excludeSkippedSlides: true))
    for blk in blocks:
      check blk.slide != 2
    check blocks.len == key.textBlocks.len - 3
    let both = key.getText(ExtractOptions(excludeNotes: true,
      excludeSkippedSlides: true))
    check both == ["Quarterly numbers", "Sales by region", "Region\tQ1\tQ2",
      "North\t10\t12", "South\t7\t9", "Group alpha", "Group beta",
      "Outer gamma", "Closing", "Thanks"].join("\n")

  test "headers and footers go without taking matching body text":
    check pages.getText(ExtractOptions(excludeHeaders: true)) ==
      ["Body one 🙂", "Footer text", "inline cell", "Body two",
      "Footer text", "Box text", "floating cell"].join("\n")
    check pages.getText(ExtractOptions(excludeFooters: true)) ==
      ["Header text", "Body one 🙂", "Footer text", "inline cell",
      "Body two", "Box text", "floating cell"].join("\n")
    check pages.getText(ExtractOptions(excludeHeaders: true,
      excludeFooters: true)) == ["Body one 🙂", "Footer text",
      "inline cell", "Body two", "Box text", "floating cell"].join("\n")

  test "keynote options leave pages and numbers alone, and vice versa":
    let all = ExtractOptions(excludeNotes: true, excludeSkippedSlides: true,
      excludeHeaders: true, excludeFooters: true)
    let book = openDocument(fixtures / "rich.numbers")
    check book.getText(all) == book.getText()
    check pages.getText(ExtractOptions(excludeNotes: true,
      excludeSkippedSlides: true)) == pages.getText()
    check key.getText(ExtractOptions(excludeHeaders: true,
      excludeFooters: true)) == key.getText()

  test "options pass through getTextReport":
    let report = key.getTextReport(strict = true,
      opts = ExtractOptions(excludeNotes: true))
    check report.text == key.getText(ExtractOptions(excludeNotes: true))

suite "content: block sources":
  test "keynote blocks know their slide, storage, and table row":
    let doc = openDocument(fixtures / "grouped-tables.key")
    let slides = doc.slides
    let blocks = doc.textBlocks
    check blocks[0].slide == 1
    check blocks[0].objectId == slides[0].titleId
    check blocks[0].objectId != 0
    var rows: seq[int]
    for blk in blocks:
      check blk.slide in 1 .. 4
      if blk.kind == tbTableRow:
        check blk.table == "Sales"
        check blk.objectId == slides[0].tables[0].id
        rows.add(blk.row)
      elif blk.kind == tbNotes and blk.slide == 3:
        check blk.objectId == slides[2].notesId
      else:
        check blk.row == 0
    check rows == @[1, 2, 3]

  test "numbers rows know their table and row":
    let doc = openDocument(fixtures / "simple.numbers")
    let blocks = doc.textBlocks
    let t = doc.tables[0]
    for blk in blocks:
      check blk.slide == 0
      if blk.kind == tbTableRow:
        check blk.table == "Table 1"
        check blk.objectId == t.id
    check blocks[^1].row == 3

  test "pages blocks know their storage, pages tables their rows":
    let pages = synthetic("sources.pages", pagesStream())
    for blk in pages.textBlocks:
      case blk.kind
      of tbHeader: check blk.objectId == 6
      of tbBody: check blk.objectId == 2
      of tbFooter: check blk.objectId == 7
      of tbTextBox: check blk.objectId == 9
      of tbTableRow:
        check blk.table in ["Inline", "Floating"]
        check blk.row == 1
        check blk.objectId in [71'u64, 81]
      else: check false

  test "equality still ignores the source fields":
    let blk = openDocument(fixtures / "simple.key").textBlocks[0]
    check blk == TextBlock(kind: tbTitle, section: "slide 1",
      text: "hello keynote")
    check blk.objectId != 0

suite "content: every layout reads the same":
  # the new fixtures as directory bundles and zips with a nested Index.zip
  for name in ["grouped-tables.key", "inline-tables.pages"]:
    let want = openDocument(fixtures / name).getText()
    var entries: OrderedTable[string, string]
    let reader = openZipArchive(fixtures / name)
    for path in reader.walkFiles:
      entries[path] = reader.extractFile(path)
    reader.close()

    test name & " as a directory bundle":
      let dir = getTempDir() / "iwork_layout_" & name
      removeDir(dir)
      defer: removeDir(dir)
      for path, data in entries:
        createDir(parentDir(dir / path))
        writeFile(dir / path, data)
      let doc = openDocument(dir)
      check doc.container.kind == ckBundle
      check doc.getText() == want

    test name & " with a nested Index.zip":
      var inner, outer: OrderedTable[string, string]
      for path, data in entries:
        if path.startsWith("Index/"): inner[path] = data
        else: outer[path] = data
      outer["Index.zip"] = createZipArchive(inner)
      let tmp = getTempDir() / "iwork_layout_nested_" & name
      writeFile(tmp, createZipArchive(outer))
      defer: removeFile(tmp)
      check openDocument(tmp).getText() == want
